export const ZONE_IDS: readonly ZoneId[] = ZONES.map((z) => z.id)

export function getZone(id: ZoneId): ZoneDefinition {
  const zone = ZONES.find((z) => z.id === id)
  if (!zone) throw new Error(`Unknown zone: ${id}`)
  return zone
}
